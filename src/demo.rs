#[derive(Clone, Copy)]
enum Plan {
    Printing { at: f32, seconds: u64 },
    Paused { at: f32, seconds: u64 },
    Idle,
    Unclear,
    OnCard,
    Away,
    Runaway,
    Halted,
    Offline,
}

struct Rig {
    name: &'static str,
    filament: &'static str,
    plan: Plan,
}

const RIGS: [Rig; 12] = [
    Rig { name: "Ender-3 Pro", filament: "PLA", plan: Plan::Printing { at: 0.62, seconds: 1800 } },
    Rig { name: "Prusa MK3S", filament: "PETG", plan: Plan::Printing { at: 0.94, seconds: 600 } },
    Rig { name: "CR-10 Smart", filament: "PLA", plan: Plan::Paused { at: 0.5, seconds: 5400 } },
    Rig { name: "Ender-3 V2", filament: "PLA", plan: Plan::Unclear },
    Rig { name: "Voron 0.2", filament: "PLA", plan: Plan::OnCard },
    Rig { name: "Creality K1", filament: "PLA", plan: Plan::Runaway },
    Rig { name: "Kobra Go", filament: "PLA", plan: Plan::Offline },
    Rig { name: "Ender-5 Plus", filament: "TPU", plan: Plan::Idle },
    Rig { name: "Artillery X1", filament: "PETG", plan: Plan::Away },
    Rig { name: "Sovol SV06", filament: "PLA", plan: Plan::Printing { at: 0.1, seconds: 3600 } },
    Rig { name: "Neptune 3", filament: "PETG", plan: Plan::Idle },
    Rig { name: "Flashforge", filament: "PLA", plan: Plan::Halted },
];

const PARTS: [(&str, &str, u64); 6] = [
    ("gearbox-housing", "PLA", 4800),
    ("spool-holder", "PETG", 7200),
    ("phone-stand", "PLA", 2400),
    ("cable-clip", "PLA", 900),
    ("enclosure-panel", "PETG", 10800),
    ("vase-lamp", "PLA", 5400),
];

fn clock(seconds: u64) -> String {
    format!("{}h {}m {}s", seconds / 3600, seconds % 3600 / 60, seconds % 60)
}

fn temperatures(filament: &str) -> (f32, f32) {
    match filament {
        "PETG" => (240.0, 80.0),
        "ABS" | "ASA" => (250.0, 100.0),
        "TPU" => (230.0, 50.0),
        _ => (210.0, 60.0),
    }
}

fn gcode_text(filament: &str, seconds: u64) -> String {
    let mut s =
        String::from("; generated by PrusaSlicer 2.9.0 on 2026-10-17 at 09:00:00 UTC\nG28\n");
    let (hot, bed) = temperatures(filament);
    s.push_str(&format!("M140 S{bed}\nM104 S{hot}\n"));
    s.push_str("M83\nG90\n");
    let layers = 90;
    for layer in 0..layers {
        let z = 0.2 + layer as f32 * 0.2;
        let half = 30.0 - layer as f32 * 0.3;
        let rings = if layer < 4 { (half / 0.45) as usize } else { 3 };
        s.push_str(&format!(";LAYER_CHANGE\n;Z:{z:.2}\nG1 Z{z:.2}\n"));
        for ring in 0..rings {
            let r = half - ring as f32 * 0.45;
            s.push_str(&format!("G1 X{:.2} Y{:.2}\n", 100.0 - r, 100.0 - r));
            for (dx, dy) in [(r, -r), (r, r), (-r, r), (-r, -r)] {
                s.push_str(&format!("G1 X{:.2} Y{:.2} E0.9\n", 100.0 + dx, 100.0 + dy));
            }
        }
    }
    s.push_str("M104 S0\nM140 S0\n");
    s.push_str(&format!("; filament used [g] = {:.2}\n", seconds as f32 / 90.0));
    s.push_str(&format!("; estimated printing time (normal mode) = {}\n", clock(seconds)));
    s.push_str(&format!("; filament_type = {filament}\n"));
    s
}

fn commands(text: &str) -> String {
    text.lines().filter_map(gcode::command).map(|c| format!("{c}\n")).collect()
}

fn write_part(dir: &Path, name: &str, filament: &str, seconds: u64) -> Result<PathBuf, String> {
    let path = dir.join("gcode").join(format!("{name}.gcode"));
    std::fs::write(&path, gcode_text(filament, seconds)).map_err(|e| e.to_string())?;
    Ok(path)
}

pub struct Farm {
    _sims: Vec<Pty>,
}

fn build(dir: &Path, count: usize) -> Result<Farm, String> {
    let now = farm::now();
    let mut config = Config::default();
    let mut queue = Queue::default();
    let mut sims = Vec::new();
    let mut parts = Vec::new();
    for (name, filament, seconds) in PARTS {
        parts.push((name, filament, seconds, write_part(dir, name, filament, seconds)?));
    }
    let find = |name: &str| parts.iter().find(|p| p.0 == name).unwrap().3.clone();
    let mut held = Vec::new();

    for n in 0..count {
        let rig =
            RIGS.get(n).unwrap_or(&Rig { name: "Ender-3", filament: "PLA", plan: Plan::Idle });
        let name =
            if n < RIGS.len() { rig.name.to_string() } else { format!("{} #{}", rig.name, n + 1) };
        let id = config.fresh_id(&name);
        let link = dir.join(format!("printer-{n}"));
        let mut script = Script { sd_lines_per_s: 300.0, heated: None, ..Default::default() };
        let mut port = link.clone();
        match rig.plan {
            Plan::Printing { at, seconds } | Plan::Paused { at, seconds } => {
                let paused = matches!(rig.plan, Plan::Paused { .. });
                let part =
                    format!("{}-{}", ["rack", "knob", "mount", "lid", "bracket"][n % 5], n + 1);
                let path = write_part(dir, &part, rig.filament, seconds)?;
                let job_id = queue.add(&path, Some(id.clone()))?;
                let job = queue.take(job_id).unwrap();
                let card = commands(&gcode_text(rig.filament, seconds));
                let lines = card.lines().count() as f32;
                script.sd_lines_per_s = lines / seconds as f32;
                script.printing = Some(sd_name(job.id));
                script.start_at = at;
                script.paused = paused;
                script.heated = Some(temperatures(rig.filament));
                script.files = vec![(sd_name(job.id), card)];
                let started = now.saturating_sub((at * seconds as f32) as u64);
                queue.running.insert(id.clone(), Running { job, started, on_printer: true });
            }
            Plan::Runaway => {
                let seconds = 3000;
                let path = write_part(dir, "calibration-cube", rig.filament, seconds)?;
                let job_id = queue.add(&path, Some(id.clone()))?;
                let job = queue.take(job_id).unwrap();
                let card = commands(&gcode_text(rig.filament, seconds));
                script.sd_lines_per_s = card.lines().count() as f32 / seconds as f32;
                script.printing = Some(sd_name(job.id));
                script.start_at = 0.2;
                script.heated = Some(temperatures(rig.filament));
                script.files = vec![(sd_name(job.id), card)];
                script.fault_after = Some((
                    Duration::from_secs(30),
                    "Thermal Runaway, system stopped! Heater decoupled".into(),
                ));
                let started = now.saturating_sub(600);
                queue.running.insert(id.clone(), Running { job, started, on_printer: true });
            }
            Plan::Away => {
                let path = write_part(dir, "hinge-pair", rig.filament, 2400)?;
                let job_id = queue.add(&path, Some(id.clone()))?;
                let job = queue.take(job_id).unwrap();
                queue.running.insert(
                    id.clone(),
                    Running { job, started: now.saturating_sub(3000), on_printer: true },
                );
            }
            Plan::Unclear => {
                queue.unclear.insert(id.clone());
            }
            Plan::OnCard => {
                let path = find("gearbox-housing");
                let text = std::fs::read_to_string(&path).map_err(|e| e.to_string())?;
                script.files = vec![(short_name(&path, 1), text)];
                held.push(("gearbox-housing", Some(id.clone())));
            }
            Plan::Halted => {
                script.fault_after =
                    Some((Duration::from_secs(6), "Printer halted. kill() called!".into()));
            }
            Plan::Offline => {
                port = PathBuf::from(format!("/dev/serial/by-id/usb-demo-printer-{n}"));
            }
            Plan::Idle => {}
        }
        if !matches!(rig.plan, Plan::Offline) {
            sims.push(spawn_pty(&link, script).map_err(|e| e.to_string())?);
        }
        config.printers.push(PrinterConfig {
            id,
            tag: format!("P{:02}", n + 1),
            name,
            link: Link::MarlinUsb { port: port.display().to_string(), baud: 115200 },
            camera: None,
            filament: Some(rig.filament.to_string()),
        });
    }

    for (name, _, _, path) in &parts {
        let printer = held.iter().find(|(n, _)| n == name).and_then(|(_, p)| p.clone());
        queue.add(path, printer)?;
    }

    config.save(&config::config_path())?;
    queue.save(&farm::queue_path())?;
    let titles: Vec<String> = config.printers.iter().map(PrinterConfig::title).collect();
    let past: [(usize, &str, u64, u64, Outcome, &str); 9] = [
        (0, "gearbox-housing", 36, 4700, Outcome::Done, ""),
        (1, "spool-holder", 30, 7100, Outcome::Done, ""),
        (4, "cable-clip", 26, 880, Outcome::Done, ""),
        (
            5,
            "enclosure-panel",
            22,
            2100,
            Outcome::Failed,
            "Thermal Runaway, system stopped! Heater decoupled",
        ),
        (3, "phone-stand", 20, 2300, Outcome::Done, ""),
        (2, "vase-lamp", 12, 900, Outcome::Cancelled, "cancelled"),
        (9, "phone-stand", 8, 2500, Outcome::Done, ""),
        (7, "cable-clip", 5, 30, Outcome::Failed, "the printer went away while it was being sent"),
        (0, "cable-clip", 2, 880, Outcome::Done, ""),
    ];
    for (who, job, hours_ago, seconds, outcome, reason) in past {
        let ended = now.saturating_sub(hours_ago * 3600);
        let printer = titles[who % titles.len()].clone();
        let record = Record {
            job: job.to_string(),
            path: find(job),
            printer,
            started: ended.saturating_sub(seconds),
            ended,
            outcome,
            reason: reason.to_string(),
            filament_g: (outcome == Outcome::Done).then_some(seconds as f32 / 90.0),
        };
        farm::append(&farm::history_path(), &record)?;
    }
    Ok(Farm { _sims: sims })
}

pub fn run(printers: usize) -> Result<(), String> {
    if printers == 0 || printers > 40 {
        return Err("the demo farm has 1 to 40 printers".into());
    }
    let dir = std::env::temp_dir().join(format!("printfarm-demo-{}", std::process::id()));
    std::fs::create_dir_all(dir.join("gcode")).map_err(|e| format!("{}: {e}", dir.display()))?;
    unsafe { std::env::set_var("PRINTFARM_HOME", &dir) };
    let result = match build(&dir, printers) {
        Ok(farm) => {
            eprintln!("demo farm in {}", dir.display());
            let shown = crate::app::run(Vec::new()).map_err(|e| e.to_string());
            drop(farm);
            shown
        }
        Err(e) => Err(e),
    };
    let _ = std::fs::remove_dir_all(&dir);
    result
}
