#![cfg(unix)]

use printfarm::printer::marlin::Marlin;
use printfarm::printer::sim::{Script, Seen, Sim, spawn};
use printfarm::printer::{Event, Job, Outcome, Printer, State};
use serialport::TTYPort;
use std::path::PathBuf;
use std::time::{Duration, Instant};

fn job(name: &str, body: &str) -> Job {
    let dir = std::env::temp_dir().join(format!("printfarm-marlin-{}-{name}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path: PathBuf = dir.join(format!("{name}.gcode"));
    std::fs::write(&path, body).unwrap();
    Job { id: 1, name: name.into(), path, printer: None, added: 0, meta: Default::default() }
}

fn part(lines: usize) -> String {
    let mut s = String::from("; generated by test\nG28 ; home\nM109 S210\n");
    for i in 0..lines {
        if i % 10 == 0 {
            s.push_str(";LAYER_CHANGE\n");
        }
        s.push_str(&format!("G1 X{} Y{} E0.1 ; move\n\n", i % 200, i % 180));
    }
    s.push_str("M104 S0\n");
    s
}

fn until(
    m: &mut Marlin,
    events: &mut Vec<Event>,
    what: &str,
    done: impl Fn(&Marlin, &[Event]) -> bool,
) {
    let t = Instant::now();
    while !done(m, events) {
        assert!(
            t.elapsed() < Duration::from_secs(20),
            "timed out waiting for {what}: {:?}",
            m.status()
        );
        m.step(events);
    }
}

fn connected(script: Script) -> (Marlin, Sim) {
    let (host, printer) = TTYPort::pair().expect("pty pair");
    let f = spawn(printer, script);
    let mut m = Marlin::attached(Box::new(host));
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "handshake", |m, _| m.status().state() == State::Idle);
    assert_eq!(m.status().machine.as_deref(), Some("Simulated Printer"));
    (m, f)
}

fn finished(events: &[Event]) -> Option<(Outcome, String)> {
    events.iter().find_map(|e| match e {
        Event::Finished { outcome, reason, .. } => Some((*outcome, reason.clone())),
        _ => None,
    })
}

fn sent_job_lines(seen: &Seen) -> Vec<String> {
    seen.commands.iter().filter(|c| c.starts_with("G1 ")).cloned().collect()
}

#[test]
fn prints_a_file_in_order_through_a_resend() {
    let (mut m, f) = connected(Script {
        corrupt_once: Some(20),
        busy_on: Some("M109 S210".into()),
        ..Default::default()
    });
    let body = part(200);
    m.start(job("order", &body)).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "the print to end", |_, ev| finished(ev).is_some());
    assert_eq!(finished(&ev).unwrap().0, Outcome::Done);
    assert_eq!(m.status().state(), State::Idle);
    let seen = f.seen.lock().unwrap();
    assert_eq!(seen.resends, 1);
    let expected: Vec<String> = body
        .lines()
        .filter_map(printfarm::gcode::command)
        .filter(|c| c.starts_with("G1 "))
        .map(String::from)
        .collect();
    assert_eq!(sent_job_lines(&seen), expected);
    assert_eq!(seen.commands.last().map(String::as_str), Some("M400"));
    drop(seen);
    until(&mut m, &mut ev, "a temperature report", |m, _| m.status().heater("bed").is_some());
    assert_eq!(m.status().heater("hotend").map(|h| h.target), Some(0.0));
}

#[test]
fn pause_holds_the_stream_and_resume_carries_on() {
    let (mut m, f) = connected(Script::default());
    m.start(job("pause", &part(5000))).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "some lines", |m, _| {
        m.status().progress.as_ref().is_some_and(|p| p.done > 2000)
    });
    m.pause().unwrap();
    assert_eq!(m.status().state(), State::Paused);
    for _ in 0..20 {
        m.step(&mut ev);
    }
    let held = sent_job_lines(&f.seen.lock().unwrap()).len();
    let t = Instant::now();
    while t.elapsed() < Duration::from_millis(400) {
        m.step(&mut ev);
    }
    assert_eq!(sent_job_lines(&f.seen.lock().unwrap()).len(), held);
    m.resume().unwrap();
    until(&mut m, &mut ev, "the print to end", |_, ev| finished(ev).is_some());
    assert_eq!(finished(&ev).unwrap().0, Outcome::Done);
    assert_eq!(sent_job_lines(&f.seen.lock().unwrap()).len(), 5000);
}

#[test]
fn cancel_stops_and_cools_down() {
    let (mut m, f) = connected(Script::default());
    m.start(job("cancel", &part(5000))).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "some lines", |m, _| {
        m.status().progress.as_ref().is_some_and(|p| p.done > 2000)
    });
    m.cancel().unwrap();
    until(&mut m, &mut ev, "the cancel", |_, ev| finished(ev).is_some());
    assert_eq!(finished(&ev).unwrap().0, Outcome::Cancelled);
    until(&mut m, &mut ev, "cool down", |_, _| {
        f.seen.lock().unwrap().commands.last().map(String::as_str) == Some("M107")
    });
    let seen = f.seen.lock().unwrap();
    assert_eq!(seen.resends, 0);
    let tail: Vec<&str> = seen.commands.iter().rev().take(4).rev().map(String::as_str).collect();
    assert!(tail[0].starts_with("M110 N"), "{tail:?}");
    assert_eq!(&tail[1..], ["M104 S0", "M140 S0", "M107"]);
    assert!(seen.commands.iter().any(|c| c == "M108"));
    assert!(sent_job_lines(&seen).len() < 5000);
    assert_eq!(m.status().state(), State::Idle);
}

#[test]
fn a_halted_printer_fails_the_job() {
    let (mut m, _f) =
        connected(Script { halt_at: Some("G1 X50 Y50 E0.1".into()), ..Default::default() });
    m.start(job("halt", &part(200))).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "the fault", |m, _| m.status().state() == State::Fault);
    let (outcome, reason) = finished(&ev).unwrap();
    assert_eq!(outcome, Outcome::Failed);
    assert!(reason.contains("halted"), "{reason}");
    assert!(m.start(job("halt2", &part(5))).is_err());
}

#[test]
fn console_commands_are_sent_and_answered() {
    let (mut m, f) = connected(Script::default());
    m.gcode("M503 ; settings\n\nM114").unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "the console", |_, _| {
        f.seen.lock().unwrap().commands.iter().any(|c| c == "M114")
    });
    let seen = f.seen.lock().unwrap();
    let i = seen.commands.iter().position(|c| c == "M503").unwrap();
    assert_eq!(seen.commands[i + 1], "M114");
    assert!(
        ev.iter()
            .any(|e| matches!(e, Event::Console(printfarm::printer::Dir::Sent, c) if c == "M503"))
    );
}

#[test]
fn a_lost_link_fails_the_job() {
    let (mut m, f) = connected(Script::default());
    m.start(job("lost", &part(20000))).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "some lines", |m, _| {
        m.status().progress.as_ref().is_some_and(|p| p.done > 2000)
    });
    drop(f);
    until(&mut m, &mut ev, "the link to drop", |m, _| m.status().state() == State::Offline);
    assert_eq!(finished(&ev).unwrap().0, Outcome::Failed);
}

#[test]
fn cancel_breaks_out_of_a_heating_wait() {
    let (mut m, f) = connected(Script { heat_rate: 1.0, ..Default::default() });
    m.start(job("heating", &part(50))).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "the heating wait", |m, _| {
        m.status().activity == Some("heating the hot end")
    });
    m.cancel().unwrap();
    until(&mut m, &mut ev, "the cool down", |m, _| {
        m.settled() && f.seen.lock().unwrap().commands.last().map(String::as_str) == Some("M107")
    });
    assert_eq!(finished(&ev).unwrap().0, Outcome::Cancelled);
    assert!(sent_job_lines(&f.seen.lock().unwrap()).is_empty());
}
