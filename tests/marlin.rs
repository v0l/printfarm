#![cfg(unix)]

use printfarm::printer::marlin::{Marlin, sd_name};
use printfarm::printer::sim::{Script, Seen, Sim, spawn};
use printfarm::printer::{Dir, Event, Job, Outcome, Printer, State};
use serialport::{SerialPort, TTYPort};
use std::path::PathBuf;
use std::time::{Duration, Instant, SystemTime};

fn job(id: u64, name: &str, body: &str) -> Job {
    let dir = std::env::temp_dir().join(format!("printfarm-marlin-{}-{name}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path: PathBuf = dir.join(format!("{name}.gcode"));
    std::fs::write(&path, body).unwrap();
    Job { id, name: name.into(), path, printer: None, added: 0, meta: Default::default() }
}

fn part(lines: usize) -> String {
    let mut s = String::from("; generated by test\nG28 ; home\nM104 S210\n");
    for i in 0..lines {
        if i % 10 == 0 {
            s.push_str(";LAYER_CHANGE\n");
        }
        s.push_str(&format!("G1 X{} Y{} E0.1 ; move\n\n", i % 200, i % 180));
    }
    s.push_str("M104 S0\n");
    s
}

fn commands(body: &str) -> String {
    body.lines().filter_map(printfarm::gcode::command).map(|c| format!("{c}\n")).collect()
}

fn until(
    m: &mut Marlin,
    events: &mut Vec<Event>,
    what: &str,
    done: impl Fn(&Marlin, &[Event]) -> bool,
) {
    let t = Instant::now();
    while !done(m, events) {
        assert!(
            t.elapsed() < Duration::from_secs(20),
            "timed out waiting for {what}: {:?}",
            m.status()
        );
        m.step(events);
    }
}

struct Bench {
    sim: Sim,
    path: String,
}

fn bench(script: Script) -> (Bench, TTYPort) {
    let (printer, host) = TTYPort::pair().expect("pty pair");
    let path = host.name().unwrap();
    (Bench { sim: spawn(printer, script), path }, host)
}

fn ready(link: Box<dyn SerialPort>, watch: Option<(Job, SystemTime)>) -> (Marlin, Vec<Event>) {
    let mut m = Marlin::attached(link);
    if let Some((job, started)) = watch {
        m.adopt(job, started, true);
    }
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "handshake", |m, _| {
        !matches!(m.status().state(), State::Connecting | State::Offline) && m.settled()
    });
    (m, ev)
}

fn connected(script: Script) -> (Marlin, Bench) {
    let (b, host) = bench(script);
    let (m, _) = ready(Box::new(host), None);
    assert_eq!(m.status().machine.as_deref(), Some("Simulated Printer"));
    (m, b)
}

fn reopen(b: &Bench) -> Box<dyn SerialPort> {
    Box::new(
        TTYPort::open(&serialport::new(&b.path, 115200).timeout(Duration::from_millis(20)))
            .unwrap(),
    )
}

fn finished(events: &[Event]) -> Option<(Outcome, String)> {
    events.iter().find_map(|e| match e {
        Event::Finished { outcome, reason, .. } => Some((*outcome, reason.clone())),
        _ => None,
    })
}

fn interrupted(events: &[Event]) -> Option<String> {
    events.iter().find_map(|e| match e {
        Event::Interrupted(_, why) => Some(why.clone()),
        _ => None,
    })
}

fn on_printer(events: &[Event]) -> bool {
    events.iter().any(|e| matches!(e, Event::OnPrinter(_)))
}

fn last_command(seen: &std::sync::Mutex<Seen>) -> Option<String> {
    seen.lock().unwrap().commands.last().cloned()
}

#[test]
fn copies_the_file_to_the_card_and_prints_it_from_there() {
    let (mut m, b) =
        connected(Script { corrupt_once: Some(20), sd_lines_per_s: 100.0, ..Default::default() });
    let body = part(400);
    m.start(job(7, "order", &body)).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "the copy", |_, ev| on_printer(ev));
    assert_eq!(b.sim.seen.lock().unwrap().resends, 1);
    {
        let card = b.sim.card.lock().unwrap();
        let file = card.files.get(&sd_name(7)).expect("file on the card");
        assert_eq!(String::from_utf8_lossy(file), commands(&body));
    }
    until(&mut m, &mut ev, "progress from the card", |m, _| {
        m.status().state() == State::Printing
            && m.status().progress.as_ref().is_some_and(|p| p.done > 0 && !p.sending)
    });
    assert!(m.status().progress.as_ref().unwrap().layer > 0);
    until(&mut m, &mut ev, "the print to end", |_, ev| finished(ev).is_some());
    assert_eq!(finished(&ev).unwrap().0, Outcome::Done);
    until(&mut m, &mut ev, "the file to be deleted", |_, _| {
        b.sim.card.lock().unwrap().files.is_empty()
    });
    assert_eq!(m.status().state(), State::Idle);
}

#[test]
fn the_print_carries_on_without_printfarm_and_is_picked_up_again() {
    let (b, host) = bench(Script { sd_lines_per_s: 100.0, ..Default::default() });
    let (mut m, _) = ready(Box::new(host), None);
    let j = job(3, "away", &part(1500));
    m.start(j.clone()).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "the copy", |_, ev| on_printer(ev));
    let started = SystemTime::now();
    until(&mut m, &mut ev, "the print to start", |m, _| {
        m.status().progress.as_ref().is_some_and(|p| p.done > 0)
    });
    drop(m);
    std::thread::sleep(Duration::from_millis(500));
    assert!(b.sim.card.lock().unwrap().open.as_ref().is_some_and(|o| o.printing));

    let (mut m, mut ev) = ready(reopen(&b), Some((j, started)));
    until(&mut m, &mut ev, "our job", |m, _| {
        m.status().state() == State::Printing
            && m.status().progress.as_ref().is_some_and(|p| p.done > 0)
    });
    assert_eq!(m.status().progress.as_ref().unwrap().job.id, 3);
    assert!(m.status().foreign.is_none());
    assert!(finished(&ev).is_none());
    until(&mut m, &mut ev, "the print to end", |_, ev| finished(ev).is_some());
    assert_eq!(finished(&ev).unwrap().0, Outcome::Done);
}

#[test]
fn a_job_that_finished_while_away_is_reported_done() {
    let (b, host) = bench(Script { sd_lines_per_s: 5000.0, ..Default::default() });
    let (mut m, _) = ready(Box::new(host), None);
    let j = job(4, "quick", &part(300));
    m.start(j.clone()).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "the copy", |_, ev| on_printer(ev));
    for _ in 0..5 {
        m.step(&mut ev);
    }
    drop(m);
    let t = Instant::now();
    while b.sim.card.lock().unwrap().finished.is_empty() {
        assert!(t.elapsed() < Duration::from_secs(10));
        std::thread::sleep(Duration::from_millis(50));
    }
    let (mut m, mut ev) = ready(reopen(&b), Some((j, SystemTime::now())));
    until(&mut m, &mut ev, "the report", |_, ev| finished(ev).is_some());
    let (outcome, reason) = finished(&ev).unwrap();
    assert_eq!(outcome, Outcome::Done);
    assert!(reason.contains("away"), "{reason}");
    until(&mut m, &mut ev, "the tidy up", |_, _| b.sim.card.lock().unwrap().files.is_empty());
}

#[test]
fn a_print_started_elsewhere_shows_as_unknown() {
    let other = commands(&part(5000));
    let (mut m, _b) = connected(Script {
        sd_lines_per_s: 50.0,
        files: vec![("BENCHY.GCO".into(), other)],
        printing: Some("BENCHY.GCO".into()),
        ..Default::default()
    });
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "the unknown job", |m, _| m.status().foreign.is_some());
    let f = m.status().foreign.clone().unwrap();
    assert!(f.file.eq_ignore_ascii_case("BENCHY.GCO"));
    assert!(f.printing && f.total > 0);
    assert_eq!(m.status().state(), State::Printing);
    assert!(m.status().progress.is_none());
    assert!(m.start(job(9, "blocked", &part(5))).is_err());
}

#[test]
fn pause_and_resume_go_to_the_card() {
    let (mut m, b) = connected(Script { sd_lines_per_s: 200.0, ..Default::default() });
    m.start(job(5, "pause", &part(3000))).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "printing", |m, _| {
        m.status().progress.as_ref().is_some_and(|p| p.done > 0 && !p.sending)
    });
    m.pause().unwrap();
    until(&mut m, &mut ev, "the pause", |_, _| {
        b.sim.card.lock().unwrap().open.as_ref().is_some_and(|o| !o.printing)
    });
    let held = b.sim.card.lock().unwrap().open.clone().unwrap().pos;
    let t = Instant::now();
    while t.elapsed() < Duration::from_millis(4000) {
        m.step(&mut ev);
    }
    assert_eq!(m.status().state(), State::Paused);
    assert_eq!(b.sim.card.lock().unwrap().open.clone().unwrap().pos, held);
    m.resume().unwrap();
    until(&mut m, &mut ev, "the resume", |_, _| {
        b.sim.card.lock().unwrap().open.as_ref().is_some_and(|o| o.pos > held)
    });
    assert_eq!(m.status().state(), State::Printing);
}

#[test]
fn cancel_on_the_card_stops_cools_and_tidies() {
    let (mut m, b) = connected(Script { sd_lines_per_s: 100.0, ..Default::default() });
    m.start(job(6, "cancel", &part(3000))).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "printing", |m, _| {
        m.status().progress.as_ref().is_some_and(|p| p.done > 0 && !p.sending)
    });
    m.cancel().unwrap();
    until(&mut m, &mut ev, "the cancel", |m, ev| finished(ev).is_some() && m.settled());
    assert_eq!(finished(&ev).unwrap().0, Outcome::Cancelled);
    let card = b.sim.card.lock().unwrap();
    assert!(card.open.is_none());
    assert!(card.files.is_empty());
    let seen = b.sim.seen.lock().unwrap();
    for c in ["M108", "M524", "M104 S0", "M140 S0", "M107"] {
        assert!(seen.commands.iter().any(|s| s == c), "{c} not sent");
    }
}

#[test]
fn cancel_while_sending_puts_the_job_back() {
    let (mut m, b) = connected(Script::default());
    m.start(job(8, "sending", &part(20000))).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "some of the copy", |m, _| {
        m.status().progress.as_ref().is_some_and(|p| p.sending && p.done > 20000)
    });
    m.cancel().unwrap();
    until(&mut m, &mut ev, "the stop", |m, ev| interrupted(ev).is_some() && m.settled());
    assert!(finished(&ev).is_none());
    assert!(b.sim.card.lock().unwrap().files.is_empty());
    assert_eq!(last_command(&b.sim.seen), Some(format!("M30 {}", sd_name(8))));
    assert_eq!(m.status().state(), State::Idle);
}

#[test]
fn closing_while_sending_leaves_the_card_tidy() {
    let (b, host) = bench(Script::default());
    let (mut m, _) = ready(Box::new(host), None);
    let j = job(10, "closing", &part(20000));
    m.start(j.clone()).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "some of the copy", |m, _| {
        m.status().progress.as_ref().is_some_and(|p| p.done > 20000)
    });
    m.leave();
    until(&mut m, &mut ev, "the stop", |m, _| m.settled());
    drop(m);
    assert!(b.sim.card.lock().unwrap().files.is_empty());
    let mut m = Marlin::attached(reopen(&b));
    m.adopt(j, SystemTime::now(), false);
    let mut ev = Vec::new();
    m.step(&mut ev);
    assert!(interrupted(&ev).is_some());
}

