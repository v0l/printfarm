#[test]
fn a_lost_link_mid_print_is_not_a_failure() {
    let (b, host) = bench(Script { sd_lines_per_s: 100.0, ..Default::default() });
    let (mut m, _) = ready(Box::new(host), None);
    m.start(job(12, "lost", &part(3000))).unwrap();
    let mut ev = Vec::new();
    until(&mut m, &mut ev, "printing", |m, _| {
        m.status().progress.as_ref().is_some_and(|p| p.done > 0 && !p.sending)
    });
    drop(b);
    until(&mut m, &mut ev, "the link to drop", |m, _| m.status().state() == State::Offline);
    assert!(finished(&ev).is_none());
    assert!(m.status().progress.is_some());
}

